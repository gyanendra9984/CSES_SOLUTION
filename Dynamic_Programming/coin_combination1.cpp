#include <bits/stdc++.h>
using namespace std;
#define ll long long int
#define mod 1000000007

void solve()
{
    int n, x;
    cin >> n >> x;
    vector<int> v(n);
    for (int i = 0; i < n; i++)
    {
        cin >> v[i];
    }
    vector<int> dp(x + 1,0);
    dp[0] = 1;
    for (int i = 1; i <= x; i++)
    {
        for (int j = 0; j < n; j++)
        {
            if (i - v[j] >= 0)
            {
                dp[i] = (dp[i] + dp[i - v[j]]) % mod;
            }
        }
    }
        cout << dp[x] << endl;
}
int main()
{
    solve();
    return 0;
}